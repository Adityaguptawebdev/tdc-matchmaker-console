import type { JourneyStatus, MembershipTier, Profile } from '@tdc/shared';

/**
 * Hand-written fictional TDC clients. Each has a coherent story so the demo reads naturally.
 * Ages are derived from dateOfBirth at runtime — never stored.
 */

type ClientSpec = Omit<
  Profile,
  'id' | 'kind' | 'status' | 'contact' | 'matchmaking' | 'createdAt' | 'updatedAt'
> & {
  id: string;
  ownerId: string;
  journeyStatus: JourneyStatus;
  tier: MembershipTier;
  joinedDaysAgo: number;
  lastContactDaysAgo: number | null;
};

const slug = (s: string) => s.toLowerCase().replace(/[^a-z]/g, '');

export function buildClients(now: Date): Profile[] {
  const iso = (daysAgo: number) => new Date(now.getTime() - daysAgo * 86_400_000).toISOString();
  return SPECS.map((s, i) => {
    const { ownerId, journeyStatus, tier, joinedDaysAgo, lastContactDaysAgo, ...profile } = s;
    return {
      ...profile,
      kind: 'client',
      status: 'active',
      contact: {
        email: `${slug(s.firstName)}.${slug(s.lastName)}@example.com`,
        phone: `+91 00000 ${String(90001 + i).padStart(5, '0')}`,
      },
      matchmaking: {
        ownerId,
        journeyStatus,
        membershipTier: tier,
        joinedAt: iso(joinedDaysAgo),
        lastContactedAt: lastContactDaysAgo === null ? null : iso(lastContactDaysAgo),
      },
      createdAt: iso(joinedDaysAgo),
      updatedAt: iso(lastContactDaysAgo ?? joinedDaysAgo),
    };
  });
}

